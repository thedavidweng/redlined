# Writes <product>/_shared/redlines.js: the redline list every page reads (previewer, stage), as a classic
# script so it also loads from file://. serve.py and record.py run this for you. Run by hand:
#   python3 _tools/sync.py
# Order: the product README table (posting order), then redline folders it doesn't list yet, alphabetically.
import json, pathlib, re

ROOT = pathlib.Path(__file__).resolve().parent.parent
FOLDER = re.compile(r'^(fix|ux|feat|ui|a11y)-[a-z0-9-]+$')


def readme_field(text, pattern, default):
    m = re.search(pattern, text, re.M)
    return m[1].strip() if m else default


def sync_product(product):
    readme = (product / 'README.md').read_text() if (product / 'README.md').exists() else ''
    listed = re.findall(r'^\|[^|\n]*\|\s*\[`([a-z0-9-]+)`\]', readme, re.M)
    on_disk = sorted(p.name for p in product.iterdir() if p.is_dir() and FOLDER.match(p.name) and (p / 'README.md').exists())
    folders = [f for f in listed if f in on_disk] + [f for f in on_disk if f not in listed]
    redlines = []
    for n, folder in enumerate(folders, 1):
        text = (product / folder / 'README.md').read_text()
        redlines.append({
            'n': n,
            'folder': folder,
            'title': readme_field(text, r'^# (.+)$', folder),
            'caption': readme_field(text, r'^\*\*Caption\*\*\s*\n\s*> (.+)$', ''),
            'clip': (product / folder / 'media' / 'clip.mp4').exists(),
        })
    stage = json.loads((product / '_shared' / 'stage.json').read_text())
    data = {'product': product.name, 'name': stage['name'], 'label': stage['label'], 'redlines': redlines}
    out = product / '_shared' / 'redlines.js'
    text = ('// Generated by _tools/sync.py from the README table and each redline README. Do not edit.\n'
            f'globalThis.REDLINED = {json.dumps(data, indent=2, ensure_ascii=False)};\n')
    if not out.exists() or out.read_text() != text:
        out.write_text(text)
    return data


def sync():
    return [sync_product(p.parent.parent) for p in sorted(ROOT.glob('*/_shared/stage.json'))]


if __name__ == '__main__':
    for data in sync():
        print(f"{data['product']}: " + ', '.join(f"{r['n']}: {r['folder']}" for r in data['redlines']))
