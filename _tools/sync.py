# Writes <product>/_shared/redlines.js: the redline list every page reads (previewer, stage), as a classic
# script so it also loads from file://. Also writes the series index: products.js (read by the home page,
# index.html) and the product table in README.md. serve.py and record.py run this for you. Run by hand:
#   python3 _tools/sync.py
# Order: the product README table (posting order), then redline folders it doesn't list yet, alphabetically.
import json, pathlib, re

ROOT = pathlib.Path(__file__).resolve().parent.parent
FOLDER = re.compile(r'^\d{2}-(?:fix|ux|feat|ui|a11y)-[a-z0-9-]+$')


def readme_field(text, pattern, default):
    m = re.search(pattern, text, re.M)
    return m[1].strip() if m else default


def sync_product(product):
    readme = (product / 'README.md').read_text() if (product / 'README.md').exists() else ''
    listed = re.findall(r'^\|[^|\n]*\|\s*\[`([a-z0-9-]+)`\]', readme, re.M)
    on_disk = sorted(p.name for p in product.iterdir() if p.is_dir() and FOLDER.match(p.name) and (p / 'README.md').exists())
    folders = [f for f in listed if f in on_disk] + [f for f in on_disk if f not in listed]
    redlines = []
    for n, folder in enumerate(folders, 1):
        text = (product / folder / 'README.md').read_text()
        redlines.append({
            'n': n,
            'folder': folder,
            'title': readme_field(text, r'^# (.+)$', folder),
            'caption': readme_field(text, r'^\*\*Caption\*\*\s*\n\s*> (.+)$', ''),
            'clip': (product / folder / 'media' / 'clip.mp4').exists(),
        })
    stage = json.loads((product / '_shared' / 'stage.json').read_text())
    first = next((r for r in redlines if (product / r['folder'] / 'media' / 'cover.webp').exists()), None)
    data = {'product': product.name, 'name': stage['name'], 'label': stage['label'],
            'about': readme_field(readme, r'^([A-Z][^\n]*?\.)(?: |$)', ''),
            'cover': f"{product.name}/{first['folder']}/media/cover.webp" if first else None,
            'icon': f'{product.name}/_shared/icon.png' if (product / '_shared' / 'icon.png').exists() else None, 'redlines': redlines}
    write(product / '_shared' / 'redlines.js', '// Generated by _tools/sync.py from the README table and each redline README. Do not edit.\n'
          f'globalThis.REDLINED = {json.dumps(data, indent=2, ensure_ascii=False)};\n')
    return data


SITE = 'https://thedavidweng.github.io/redlined/'
TABLE = re.compile(r'(<!-- products:start -->\n).*?(<!-- products:end -->)', re.S)


def write(path, text):
    if not path.exists() or path.read_text() != text:
        path.write_text(text)


def sync_index(products):
    entries = [{k: d[k] for k in ('product', 'name', 'label', 'about', 'cover', 'icon')} | {'count': len(d['redlines'])} for d in products]
    write(ROOT / 'products.js', '// Generated by _tools/sync.py from each <product>/. Do not edit.\n'
          f'globalThis.REDLINED_PRODUCTS = {json.dumps(entries, indent=2, ensure_ascii=False)};\n')
    rows = ['| Product | Surface | Redlines | Demo |', '| --- | --- | --- | --- |']
    rows += [f"| [{e['name']}]({e['product']}/) | {e['label'].split(' · ', 1)[-1]} | {e['count']} | [Open]({SITE}{e['product']}/) |" for e in entries]
    readme = ROOT / 'README.md'
    write(readme, TABLE.sub(lambda m: m[1] + '\n'.join(rows) + '\n' + m[2], readme.read_text()))


def sync():
    products = [sync_product(p.parent.parent) for p in sorted(ROOT.glob('*/_shared/stage.json'))]
    sync_index(products)
    return products


if __name__ == '__main__':
    for data in sync():
        print(f"{data['product']}: " + ', '.join(f"{r['n']}: {r['folder']}" for r in data['redlines']))
