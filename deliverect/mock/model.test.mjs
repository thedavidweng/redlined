import assert from 'node:assert/strict';
import './model.js';
const { orders, locations, filterOrders } = globalThis.DeliverectModel;
const all = { channel: [], brand: [], type: [], location: [...locations] };
assert.equal(new Set(orders.map(order => order.id)).size, orders.length);
assert.equal(filterOrders(orders, all).length, 12);
assert.equal(filterOrders(orders, all).filter(order => order.status === 'ready').length, 5);
assert.equal(filterOrders(orders, { ...all, brand: ["Mindy's"] }).length, 3);
assert.equal(filterOrders(orders, { ...all, channel: ['NextGen'], type: ['Delivery'] }).length, 0);
assert.equal(filterOrders(orders, { ...all, location: [] }).length, 0);
assert.deepEqual(filterOrders(orders, { ...all, brand: ['Thai Away Moon'], channel: ['NextGen'], type: ['Pickup'], location: ['Thai Away Moon'] }).map(order => order.id), ['E75F0F17']);
assert.equal(filterOrders(orders, { ...all, brand: ["Mindy's", 'Hello Maki'] }).length, 4);
console.log('Pickup Manager fixture and filter checks passed.');

const { managedOrders, searchOrders, setOrderStatus } = globalThis.DeliverectModel;
assert.equal(filterOrders(managedOrders, all).length, 12);
assert.deepEqual(searchOrders(managedOrders, ' #9EF895ED ').map(order => order.id), ['9EF895ED']);
assert.deepEqual(searchOrders(managedOrders, 'adil').map(order => order.id), ['423372B6']);
assert.equal(searchOrders(managedOrders, 'DoOrDaSh').length, 3);
assert.deepEqual(searchOrders(managedOrders, 'jean-felix').map(order => order.id), ['F7F39CCB']);
assert.equal(searchOrders(managedOrders, 'missing').length, 0);
assert.equal(searchOrders(managedOrders, '  ').length, 12);
const ready = setOrderStatus(managedOrders, '991D0363', 'ready');
assert.equal(ready.find(order => order.id === '991D0363').status, 'ready');
assert.equal(managedOrders.find(order => order.id === '991D0363').status, 'preparing');
const pickedUp = setOrderStatus(ready, '991D0363', 'pickedup');
assert.equal(pickedUp.filter(order => ['ready', 'preparing'].includes(order.status)).length, 11);
assert.equal(setOrderStatus(orders, '9EF895ED', 'pickedup').find(order => order.id === '9EF895ED').status, 'pickedup');
console.log('Management search, location filtering, and status changes passed.');
