# Storyboard for 01-ux-swipe-to-confirm. `d` is the Director from _tools/record.py.
async def run(d):
    await d.intro()
    b = await d.box('before', '.action-button', 'Rohan')
    await d.glide(*d.center(b), 0.9)
    await d.wait(0.25)
    await d.tap()
    await d.wait(0.15)
    await d.wait(1.6)

    await d.focus('after')
    k = await d.box('after', '.p-swipe button', 'Rohan')
    await d.glide(*d.center(k), 1.0)
    await d.wait(0.25)
    await d.tap()
    await d.wait(1.3)
    track = await d.box('after', '.p-swipe', 'Rohan')
    await d.js('stage.press(true)')
    await d.page.mouse.down()
    await d.wait(0.12)
    await d.glide(track['x'] + track['width'] - 18, d.y, 0.75)
    await d.wait(0.08)
    await d.page.mouse.up()
    await d.js('stage.press(false)')
    await d.lift()
    await d.wait(1.5)
    await d.focus(None)
    await d.outro()
