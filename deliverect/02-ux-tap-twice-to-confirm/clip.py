# Storyboard for 02-ux-tap-twice-to-confirm. `d` is the Director from _tools/record.py.
async def run(d):
    await d.intro()
    b = await d.box('before', '.action-button', 'Ronan')
    await d.glide(*d.center(b), 0.9)
    await d.wait(0.25)
    await d.tap()
    await d.wait(0.15)
    await d.wait(1.6)

    await d.focus('after')
    a = await d.box('after', '.action-button', 'Ronan')
    await d.glide(*d.center(a), 1.0)
    await d.wait(0.25)
    await d.tap(0.05)
    await d.wait(0.07)
    await d.tap(0.05)
    await d.wait(1.5)
    await d.tap()
    await d.lift()
    await d.wait(1.6)
    await d.focus(None)
    await d.outro()
